#!/usr/bin/env node

// ===========================================================================
// BROWSER RUNTIME coverage gate for Darkmown.
//
// WHY THIS GATE EXISTS
// --------------------
// `scripts/test-coverage-gate.mjs` measures the unit suite under Node's V8
// coverage, but the browser-served framework scripts — `src/runtime.js` (the
// reactive core) and `src/behaviors/*.js` — never execute inside Node, so they
// sit in that gate's NOT_MEASURED disclosure list. Their real net is the
// Playwright e2e suite driving a real browser. This gate makes that net
// MEASURED instead of asserted:
//
//   1. `tests/e2e/coverage.js` (the fixture every e2e spec imports) records V8
//      coverage with Playwright's `page.coverage` API — Chromium-only — and
//      writes the entries for `/__wd/runtime.js` and `/__wd/behaviors/*.js`
//      into `.runtime-coverage/`, one JSON file per test.
//   2. This script merges every entry per URL with UNION semantics (a byte
//      counts as covered if ANY test executed it), converts covered bytes to
//      LINE coverage, and gates each file against its threshold in
//      `.runtime-coverage-snapshot.json`.
//
// HOW BYTES BECOME LINES, PER FILE KIND
// -------------------------------------
//   * `/__wd/behaviors/*.js` is served as the comment-stripped
//     `src/behaviors/*.js` (see `emitBehaviors` in src/builder.js). Comment
//     stripping moves no executable byte, so coverage is computed DIRECTLY on
//     the served source the browser reports, with the same approximation the
//     Node gate uses: a line is executable when it holds a non-whitespace byte
//     inside some V8 function range, and hit when any such byte ran.
//   * `/__wd/runtime.js` is served MINIFIED (`src/runtime.min.js`), so its
//     bytes do not line up with `src/runtime.js`. The served sourcemap
//     (`src/runtime.min.js.map`, committed, with `sourcesContent`) maps every
//     generated segment back to a source line; this gate carries its own tiny
//     base64-VLQ decoder (no dependency) and counts a source line as
//     executable when a mapping lands on it at a non-whitespace line, and hit
//     when the generated byte that mapping points at was executed. The mapping
//     is segment-granular, not statement-granular, so this number tracks the
//     true line coverage but is not statement-perfect; thresholds are set
//     against what the suite actually achieves, which is what a regression
//     gate needs.
//
// THE SAME ANTI-SELF-DECEPTION RULES AS THE NODE GATE
// ---------------------------------------------------
//   * THE 0/0 LOOPHOLE IS CLOSED. A measured file whose coverage directory has
//     ZERO entries for it (collection broke, the fixture was bypassed, the
//     build stopped shipping the file) is a gate FAILURE, never a vacuous 100.
//   * The snapshot is checked both ways: a threshold entry naming a file this
//     gate does not measure is stale and fails; a measured file with no
//     threshold entry fails too. The exclusion list cannot rot in either
//     direction.
//   * Thresholds live in a COMMITTED snapshot (`.runtime-coverage-snapshot.json`,
//     mirroring `.size-snapshot.json`'s role for bytes), each with a note
//     stating why it sits where it does.
//
// TESTABILITY
//   Everything except the filesystem walk is pure and exported
//   (`lineStartOffsets`, `unionEntryBytes`, `directLineCoverage`,
//   `parseMappings`, `mappedLineCoverage`, `scoreFile`, `gateFailures`,
//   `staleSnapshotEntries`, `renderReport`) so
//   `tests/gate-runtime-coverage.test.js` drives the logic with synthetic
//   entries — no browser. Nothing runs on import: the CLI body lives in
//   `main()` behind an entry-point check.
// ===========================================================================

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

/**
 * The served framework scripts this gate measures, keyed by URL path, with the
 * repo file they stand for and how covered bytes become source lines.
 * `via: "sourcemap"` maps minified bytes through the committed map;
 * `via: "served-source"` measures the comment-stripped served text directly.
 * @type {Map<string, { src: string, via: "sourcemap" | "served-source", map?: string, served?: string }>}
 */
export const MEASURED = new Map([
  [
    "/__wd/runtime.js",
    {
      src: "runtime.js",
      via: "sourcemap",
      map: "runtime.min.js.map",
      served: "runtime.min.js"
    }
  ],
  ["/__wd/behaviors/carousel.js", { src: "behaviors/carousel.js", via: "served-source" }],
  ["/__wd/behaviors/sortable.js", { src: "behaviors/sortable.js", via: "served-source" }]
]);

/**
 * Offset of the first byte of every line (0-based) in `source`.
 * @param {string} source
 * @returns {number[]}
 */
export function lineStartOffsets(source) {
  const starts = [0];
  for (let i = 0; i < source.length; i++) {
    if (source[i] === "\n") starts.push(i + 1);
  }
  return starts;
}

/**
 * Merge Playwright coverage entries for ONE url into per-byte execution
 * status with union semantics. Each entry is one test's report for the script:
 * `{ source, functions: [{ ranges: [{ startOffset, endOffset, count }] }] }`.
 *
 * Within one entry, nested ranges are processed parent-first so a child range
 * with count 0 carves its bytes OUT of a covered parent (block coverage). That
 * carve-out stays LOCAL to the entry — across entries a byte is covered if any
 * entry executed it, which is what makes parallel workers and per-test files
 * merge correctly.
 * @param {{ source?: string, functions?: { ranges?: { startOffset: number, endOffset: number, count: number }[] }[] }[]} entries
 * @returns {{ source: string, inRange: Uint8Array, covered: Uint8Array, sourceMismatch: boolean }}
 */
export function unionEntryBytes(entries) {
  const source = entries.find((entry) => typeof entry.source === "string")?.source ?? "";
  const sourceMismatch = entries.some(
    (entry) => typeof entry.source === "string" && entry.source !== source
  );
  const inRange = new Uint8Array(source.length);
  const covered = new Uint8Array(source.length);
  for (const entry of entries) {
    const localIn = new Uint8Array(source.length);
    const localCov = new Uint8Array(source.length);
    const ranges = [];
    for (const fn of entry.functions ?? []) {
      for (const range of fn.ranges ?? []) ranges.push(range);
    }
    ranges.sort((a, b) => a.startOffset - b.startOffset || b.endOffset - a.endOffset);
    for (const range of ranges) {
      const executed = range.count > 0 ? 1 : 0;
      const end = Math.min(range.endOffset, source.length);
      for (let i = range.startOffset; i < end; i++) {
        localIn[i] = 1;
        localCov[i] = executed;
      }
    }
    for (let i = 0; i < source.length; i++) {
      if (localIn[i]) inRange[i] = 1;
      if (localCov[i]) covered[i] = 1;
    }
  }
  return { source, inRange, covered, sourceMismatch };
}

/**
 * Line ratio over a source measured directly (the served-source kind). A line
 * is executable when a non-whitespace byte of it falls inside a function
 * range, and hit when any such byte executed.
 * @param {string} source
 * @param {Uint8Array} inRange
 * @param {Uint8Array} covered
 * @returns {{ total: number, hit: number }}
 */
export function directLineCoverage(source, inRange, covered) {
  let total = 0;
  let hit = 0;
  let exec = false;
  let seen = false;
  let nonWs = false;
  const finalize = () => {
    if (exec && nonWs) {
      total++;
      if (seen) hit++;
    }
    exec = false;
    seen = false;
    nonWs = false;
  };
  for (let i = 0; i < source.length; i++) {
    const ch = source[i];
    if (ch === "\n") {
      finalize();
      continue;
    }
    if (ch !== " " && ch !== "\t" && ch !== "\r") nonWs = true;
    if (inRange[i]) {
      exec = true;
      if (covered[i]) seen = true;
    }
  }
  finalize();
  return { total, hit };
}

const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const B64_VALUE = new Map([...B64].map((ch, i) => [ch, i]));

/**
 * Decode one base64-VLQ segment (a comma-free run of the mappings string) into
 * its signed delta fields. Exported through `parseMappings`; not part of the
 * public surface on its own.
 * @param {string} segment
 * @returns {number[]}
 */
function decodeSegment(segment) {
  const fields = [];
  let value = 0;
  let shift = 0;
  for (const ch of segment) {
    const digit = B64_VALUE.get(ch);
    if (digit === undefined) throw new Error(`Bad sourcemap VLQ digit: ${ch}`);
    value |= (digit & 31) << shift;
    if (digit & 32) {
      shift += 5;
      continue;
    }
    const negative = value & 1;
    const field = value >> 1;
    fields.push(negative ? -field : field);
    value = 0;
    shift = 0;
  }
  if (shift > 0) throw new Error("Truncated sourcemap VLQ segment");
  return fields;
}

/**
 * Parse a sourcemap v3 `mappings` string into absolute segments. Fields are
 * delta-encoded: generated column resets per line, source index/line/column
 * accumulate across the whole string. Segments with fewer than 4 fields carry
 * no source position and are dropped.
 * @param {string} mappings
 * @returns {{ genLine: number, genCol: number, srcIndex: number, srcLine: number, srcCol: number }[]}
 */
export function parseMappings(mappings) {
  const segments = [];
  let srcIndex = 0;
  let srcLine = 0;
  let srcCol = 0;
  const lines = mappings.split(";");
  for (let genLine = 0; genLine < lines.length; genLine++) {
    const line = lines[genLine];
    if (!line) continue;
    let genCol = 0;
    for (const part of line.split(",")) {
      const fields = decodeSegment(part);
      genCol += fields[0];
      if (fields.length < 4) continue;
      srcIndex += fields[1];
      srcLine += fields[2];
      srcCol += fields[3];
      segments.push({ genLine, genCol, srcIndex, srcLine, srcCol });
    }
  }
  return segments;
}

/**
 * Line ratio over the ORIGINAL source of a minified script, via its sourcemap.
 * A source line is executable when some mapping segment points into it from a
 * generated byte that V8 reported inside a function range, on a source line
 * that is not blank; it is hit when any such generated byte executed. Only
 * source index 0 counts — this gate measures exactly one original file.
 * @param {{ generated: string, original: string, mappings: string,
 *   inRange: Uint8Array, covered: Uint8Array }} args
 * @returns {{ total: number, hit: number }}
 */
export function mappedLineCoverage({ generated, original, mappings, inRange, covered }) {
  const genStarts = lineStartOffsets(generated);
  const origLines = original.split("\n");
  const instrumented = new Set();
  const hitLines = new Set();
  for (const seg of parseMappings(mappings)) {
    if (seg.srcIndex !== 0) continue;
    const start = genStarts[seg.genLine];
    if (start === undefined) continue;
    const offset = start + seg.genCol;
    if (offset >= inRange.length || !inRange[offset]) continue;
    const lineText = origLines[seg.srcLine] ?? "";
    if (!/\S/.test(lineText)) continue;
    instrumented.add(seg.srcLine);
    if (covered[offset]) hitLines.add(seg.srcLine);
  }
  return { total: instrumented.size, hit: hitLines.size };
}

/**
 * Score ONE file. Zero executable lines is UNMEASURED (`pct: null`), never a
 * vacuous 100% — the same loophole the Node gate closed.
 * @param {string} url
 * @param {number} total
 * @param {number} hit
 * @returns {{ url: string, total: number, hit: number, pct: number | null, unmeasured: boolean }}
 */
export function scoreFile(url, total, hit) {
  if (total <= 0) return { url, total: 0, hit: 0, pct: null, unmeasured: true };
  return { url, total, hit, pct: (hit / total) * 100, unmeasured: false };
}

/**
 * Snapshot entries naming a file this gate does not measure. A stale entry is
 * a silent hole waiting for a URL to be reused, so it fails the gate.
 * @param {Record<string, unknown>} files The snapshot's `files` object.
 * @param {Map<string, unknown>} [measured]
 * @returns {string[]}
 */
export function staleSnapshotEntries(files, measured = MEASURED) {
  return Object.keys(files).filter((url) => !measured.has(url));
}

/**
 * The gate itself: every reason this run must exit non-zero, as printable
 * lines. An empty array means PASS.
 * @param {{ files: (ReturnType<typeof scoreFile> & { entries: number, src: string })[] }} report
 * @param {{ files: Record<string, { threshold: number }> }} snapshot
 * @param {Map<string, unknown>} [measured]
 * @returns {string[]}
 */
export function gateFailures(report, snapshot, measured = MEASURED) {
  const failures = [];
  for (const url of staleSnapshotEntries(snapshot.files, measured)) {
    failures.push(
      `FAIL: .runtime-coverage-snapshot.json sets a threshold for ${url}, which this gate does` +
        ` not measure — prune the stale entry.`
    );
  }
  for (const file of report.files) {
    const entry = snapshot.files[file.url];
    if (!entry) {
      failures.push(
        `FAIL: ${file.url} is measured but has no threshold in .runtime-coverage-snapshot.json.` +
          ` Add one (with a note) so a regression has something to trip.`
      );
      continue;
    }
    if (file.entries === 0) {
      failures.push(
        `FAIL: ${file.url} (src/${file.src}) produced ZERO coverage entries — it is unmeasured,` +
          ` not covered. The e2e collection (tests/e2e/coverage.js) must run on the chromium` +
          ` project before this gate.`
      );
      continue;
    }
    if (file.unmeasured) {
      failures.push(
        `FAIL: ${file.url} (src/${file.src}) has ZERO executable lines in its coverage — the` +
          ` measurement itself is broken (0/0 is not 100%).`
      );
      continue;
    }
    if (/** @type {number} */ (file.pct) + 1e-9 < entry.threshold) {
      failures.push(
        `FAIL: ${file.url} (src/${file.src}) line coverage ${/** @type {number} */ (file.pct).toFixed(2)}%` +
          ` is below the snapshot threshold ${entry.threshold}%. Extend the e2e suite, or lower the` +
          ` threshold deliberately with a note saying why.`
      );
    }
  }
  return failures;
}

/**
 * Render the human report: per-file line coverage with its threshold.
 * @param {{ files: (ReturnType<typeof scoreFile> & { entries: number, src: string })[],
 *   covFiles: number, warnings: string[] }} report
 * @param {{ files: Record<string, { threshold: number }> }} snapshot
 * @returns {string[]}
 */
export function renderReport(report, snapshot) {
  const fmt = (/** @type {number} */ n) => `${n.toFixed(2)}%`.padStart(10);
  const width = Math.max(20, ...report.files.map((f) => f.url.length));
  const out = [
    "",
    "=== Darkmown browser runtime coverage (e2e gate) ===",
    `Merged ${report.covFiles} raw coverage file(s) from .runtime-coverage/ (chromium e2e leg).`,
    "src/runtime.js is mapped through the committed sourcemap; behaviors are measured on the",
    "served comment-stripped source. Union semantics: a byte counts if ANY test executed it.",
    "",
    `  ${"served file".padEnd(width)} | ${"line %".padStart(10)} | lines (hit/total) | threshold | entries`
  ];
  for (const f of report.files) {
    const pct = f.unmeasured ? "UNMEASURED".padStart(10) : fmt(/** @type {number} */ (f.pct));
    const threshold = snapshot.files[f.url]?.threshold;
    out.push(
      `  ${f.url.padEnd(width)} | ${pct} | ${String(`${f.hit}/${f.total}`).padStart(13)} |` +
        ` ${String(threshold ?? "none").padStart(9)} | ${f.entries}`
    );
  }
  for (const warning of report.warnings) out.push(`  warning: ${warning}`);
  return out;
}

/**
 * Read the raw coverage directory and group entries by served URL path.
 * @param {string} covDir
 * @returns {{ byUrl: Map<string, object[]>, covFiles: number }}
 */
function readCoverageDir(covDir) {
  const byUrl = new Map();
  let covFiles = 0;
  if (!existsSync(covDir)) return { byUrl, covFiles };
  for (const name of readdirSync(covDir)) {
    if (!name.endsWith(".json")) continue;
    let entries;
    try {
      entries = JSON.parse(readFileSync(join(covDir, name), "utf8"));
    } catch {
      continue; // partially written file — skip
    }
    if (!Array.isArray(entries)) continue;
    covFiles++;
    for (const entry of entries) {
      let pathname;
      try {
        pathname = new URL(/** @type {{ url: string }} */ (entry).url).pathname;
      } catch {
        continue;
      }
      if (!byUrl.has(pathname)) byUrl.set(pathname, []);
      /** @type {object[]} */ (byUrl.get(pathname)).push(entry);
    }
  }
  return { byUrl, covFiles };
}

function main() {
  const repoRoot = process.cwd();
  const covDir = resolve(repoRoot, process.argv[2] ?? ".runtime-coverage");
  const snapshotPath = resolve(repoRoot, process.argv[3] ?? ".runtime-coverage-snapshot.json");

  if (!existsSync(snapshotPath)) {
    console.error(`FAIL: snapshot not found: ${snapshotPath}`);
    process.exit(1);
  }
  const snapshot = JSON.parse(readFileSync(snapshotPath, "utf8"));

  const { byUrl, covFiles } = readCoverageDir(covDir);
  const warnings = [];
  const files = [];
  for (const [url, spec] of MEASURED) {
    const entries = byUrl.get(url) ?? [];
    let row;
    if (entries.length === 0) {
      row = { ...scoreFile(url, 0, 0), entries: 0, src: spec.src };
    } else {
      const { source, inRange, covered, sourceMismatch } = unionEntryBytes(entries);
      if (sourceMismatch) {
        warnings.push(
          `${url}: not every coverage entry carried identical source (the served bytes changed` +
            ` mid-run); measured against the first entry's source.`
        );
      }
      let total;
      let hit;
      if (spec.via === "sourcemap") {
        const map = JSON.parse(
          readFileSync(join(repoRoot, "src", /** @type {string} */ (spec.map)), "utf8")
        );
        const original = map.sourcesContent?.[0];
        if (typeof original !== "string") {
          console.error(`FAIL: src/${spec.map} carries no sourcesContent — cannot map coverage.`);
          process.exit(1);
        }
        ({ total, hit } = mappedLineCoverage({
          generated: source,
          original,
          mappings: map.mappings,
          inRange,
          covered
        }));
      } else {
        ({ total, hit } = directLineCoverage(source, inRange, covered));
      }
      row = { ...scoreFile(url, total, hit), entries: entries.length, src: spec.src };
    }
    files.push(row);
  }

  for (const line of renderReport({ files, covFiles, warnings }, snapshot)) {
    console.log(line);
  }
  console.log("");

  const failures = gateFailures({ files }, snapshot);
  if (failures.length) {
    for (const message of failures) console.error(message);
    process.exit(1);
  }
  console.log(
    `PASS: browser runtime coverage meets every snapshot threshold (${files.length} files measured).`
  );
}

// Only run the CLI when this file IS the entry point — importing it (the unit
// test does) must not read the filesystem or exit.
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) main();
