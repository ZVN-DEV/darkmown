// Bundle the browser playground: the framework's fs-free `compileFromMemory`
// plus markdown-it and a common-language highlight.js subset, compiled to ONE
// self-contained ESM asset shipped as the playground page's colocated script
// (`site/pages/playground/index.js`). The Node builtins the compile path
// touches (`node:path`, `node:crypto`) are aliased to tiny browser shims; the
// image measurer needs no shim, since it is first-party pure JS over a
// Uint8Array (the memory compile never actually reads an image anyway).
//
// The bundle is COMMITTED, so `npm run build` needs no bundler. Rebuild it with
// `npm run build:playground` whenever the compiler or this entry changes.
// Forgetting is not silent: `node scripts/build-playground.mjs --check` (wired
// into CI and prepublish:check) rebuilds in memory and fails on a byte
// difference, exactly like the runtime artifact's `--check`. Nothing
// regenerates the file behind your back — a regenerated file nobody commits is
// drift with the alarm disconnected.
//
// DETERMINISM: same sources + same esbuild version (exact-pinned in
// package.json) ⇒ same bytes. That is what makes the drift guard a real guard.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.join(here, "..");
const shims = path.join(here, "playground", "shims");
const outfile = path.join(repoRoot, "site/pages/playground/index.js");

/**
 * Produce the playground bundle in memory. No writes, so both `main()` and
 * `--check` build the exact same bytes.
 * @returns {Promise<string>} The exact bytes (utf8) of the bundle.
 */
async function buildPlayground() {
  const result = await build({
    entryPoints: [path.join(here, "playground", "entry.js")],
    outfile,
    bundle: true,
    write: false,
    format: "esm",
    platform: "browser",
    target: ["es2020"],
    minify: true,
    legalComments: "none",
    logLevel: "warning",
    banner: {
      js: "// Generated by scripts/build-playground.mjs — do not edit. Rebuild: npm run build:playground"
    },
    alias: {
      "node:path": path.join(shims, "path.js"),
      "node:crypto": path.join(shims, "crypto.js"),
      // A smaller, common-languages-only highlight.js keeps the bundle sane; the
      // playground only ever highlights mainstream languages in fenced code.
      "highlight.js": "highlight.js/lib/common"
    }
  });

  const jsOut = result.outputFiles.find((file) => file.path.endsWith(".js"));
  if (!jsOut) throw new Error("build:playground — esbuild produced no js output");
  return jsOut.text;
}

async function main() {
  const check = process.argv.includes("--check");
  const fresh = await buildPlayground();
  const rel = path.relative(repoRoot, outfile).split(path.sep).join("/");

  if (check) {
    const committed = fs.existsSync(outfile) ? fs.readFileSync(outfile, "utf8") : null;
    if (committed !== fresh) {
      console.error(
        `build:playground --check — ${rel} does not match a fresh build.\n` +
          "Run `npm run build:playground` and commit the result."
      );
      process.exit(1);
    }
    console.log(
      `build:playground --check — up to date (${(fresh.length / 1024).toFixed(1)} KB, ${rel}).`
    );
    return;
  }

  fs.writeFileSync(outfile, fresh);
  console.log(`playground bundle: ${(fresh.length / 1024).toFixed(1)} KB → ${rel}`);
}

// Importing this file must not build or exit.
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) await main();
