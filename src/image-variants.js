// ---------------------------------------------------------------------------
// BUILD-TIME RESPONSIVE IMAGE VARIANTS (2.9.0).
//
// The 2.8.0 `@<width>` convention wires srcset entries for variants the AUTHOR
// already made; this pre-pass makes them itself. Before routes compile, the
// builder scans `site/pages` for raster photos (`.jpg`/`.jpeg`/`.png`/`.webp`),
// and for each one large enough to be worth it writes resized `name@<width>.ext`
// siblings into `dist/` at their final served paths and hands the compiler a
// map of what was generated, so markdown.js's srcset wiring treats a generated
// variant exactly like an author-provided one. The author convention still
// wins: a `name@640.jpg` already in the source tree is never overwritten, and
// that width is simply not generated.
//
// Resizing needs sharp, and sharp is an OPTIONAL dependency, so every sharp
// touch is quarantined behind a seam: the actual resize runs in a child
// process (src/image-variant-resize.js) that dynamic-imports sharp and reports
// `unavailable` instead of throwing when it is absent. Without sharp the build
// is byte-identical to 2.8.0 plus ONE hint naming the images that could have
// gained variants. A corrupt image or a sharp failure on one file is a hint
// for that file; the build never fails over an image.
//
// Resizes are cached in `node_modules/.cache/darkmown-images/` keyed by
// content hash + width, so a second build does zero sharp work for unchanged
// images (and needs no sharp at all when everything is cached). The cache
// lives under node_modules, which every project's .gitignore already excludes.
//
// The build is synchronous, sharp is not — that is the whole reason for the
// child process. `buildSite` stays a sync API; one `spawnSync` per build runs
// all pending resizes, and a fully cached build spawns nothing.
// ---------------------------------------------------------------------------

import { spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { imageSize } from "./compiler/image-size.js";

/**
 * @typedef {import("./config.js").Paths} Paths
 */

/**
 * One resize handed to the worker: shrink `source` to `width` pixels wide and
 * write it (in its own format) to `out`, the cache path.
 * @typedef {object} ResizeJob
 * @property {string} source Absolute path of the original image.
 * @property {string} out Absolute cache path the resized variant is written to.
 * @property {number} width Target width in pixels (always below the intrinsic).
 * @property {"jpeg" | "png" | "webp"} format Output encoder, from the source extension.
 */

/**
 * What the worker reports back. `unavailable` means sharp could not be loaded
 * at all (not installed, or a broken native binding) — every pending image
 * then ships without variants. `failed` carries one entry per image that
 * sharp itself rejected (corrupt payload, unsupported encoding).
 * @typedef {object} ResizeResult
 * @property {boolean} unavailable
 * @property {{ file: string, width: number, error: string }[]} failed
 */

/**
 * The pre-pass result: `variants` is the map the compiler's srcset wiring
 * consults (original's ABSOLUTE source path → sorted widths generated into
 * dist), and the counts feed the build summary. `unavailable` marks the
 * sharp-absent build (which is otherwise identical to not having the feature).
 * @typedef {object} ImageVariantPlan
 * @property {Map<string, number[]>} variants
 * @property {number} generated Variants resized this build.
 * @property {number} cached Variants served from the on-disk cache.
 * @property {boolean} unavailable sharp could not be loaded.
 */

/** The widths generated by default, both comfortably under a typical source. */
export const DEFAULT_VARIANT_WIDTHS = [640, 1280];

/** The raster formats sharp resizes; everything else (svg, gif, avif) passes through. */
const RASTER_EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".webp"]);

/** An image at or below this width is already small everywhere — skip it silently. */
const SMALL_IMAGE_MAX_WIDTH = 700;

/** The cache root, relative to the project. Under node_modules, so already ignored. */
const CACHE_DIR = "node_modules/.cache/darkmown-images";

const WORKER_PATH = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "image-variant-resize.js"
);

/**
 * Scan `site/pages` for raster images and generate `@<width>` variants into
 * `dist`, returning the variant map the compiler wires into srcsets.
 *
 * Skips, none of them errors: `@<width>` variant files themselves (they are
 * output, not sources), hidden-path and symlinked files (mirroring
 * `emitPageAssets`, which would never publish them), images at or under 700px
 * wide (already small), widths at or above the intrinsic size (never
 * upscale), and widths the author already provided (their file wins). An image
 * whose dimensions cannot be read, and one sharp fails on, get a hint naming
 * the file and ship without variants.
 * @param {Paths} paths
 * @param {{ widths?: number[], cacheDir?: string, quiet?: boolean,
 *   runJobs?: (jobs: ResizeJob[]) => ResizeResult }} [options]
 *   `widths` overrides {@link DEFAULT_VARIANT_WIDTHS}. `quiet` suppresses the
 *   hints (dev-server rebuilds, which already printed them at the initial
 *   build). `runJobs` is the resize seam — the default spawns the worker
 *   process; tests inject fakes for the unavailable/crash paths.
 * @returns {ImageVariantPlan}
 */
export function generateImageVariants(paths, options = {}) {
  const widths = options.widths ?? DEFAULT_VARIANT_WIDTHS;
  const cacheDir = options.cacheDir ?? path.join(paths.cwd, CACHE_DIR);
  const runJobs = options.runJobs ?? runResizeJobs;
  const hint = options.quiet ? () => {} : (/** @type {string} */ m) => console.warn(`hint: ${m}`);
  /** @type {Map<string, number[]>} */
  const variants = new Map();
  const stats = { generated: 0, cached: 0, unavailable: false };

  /** @type {ResizeJob[]} */
  const pending = [];
  /** @type {{ job: ResizeJob, distOut: string }[]} */
  const waiting = [];
  /** @type {string[]} Project-relative paths of images with uncached work, for the sharp-absent hint. */
  const needingSharp = [];

  /**
   * Record one materialized variant: copy it from the cache to its served
   * path and add its width to the compiler map.
   * @param {string} source Absolute path of the original.
   * @param {number} width
   * @param {string} cacheFile
   * @param {string} distOut
   */
  const emitVariant = (source, width, cacheFile, distOut) => {
    fs.mkdirSync(path.dirname(distOut), { recursive: true });
    fs.copyFileSync(cacheFile, distOut);
    const list = variants.get(source) ?? [];
    list.push(width);
    variants.set(source, list);
  };

  if (fs.existsSync(paths.routesRoot)) {
    for (const file of walk(paths.routesRoot)) {
      const ext = path.extname(file).toLowerCase();
      if (!RASTER_EXTENSIONS.has(ext)) continue;
      const stem = path.basename(file, ext);
      // A `name@640.jpg` file IS a variant (the author's, or one a previous
      // run was asked to leave alone) — never treated as a source.
      if (/@\d+$/.test(stem)) continue;
      const rel = path.relative(paths.routesRoot, file);
      if (hasHiddenPathSegment(rel) || fs.lstatSync(file).isSymbolicLink()) continue;
      /** @type {Uint8Array} */
      let bytes;
      try {
        bytes = fs.readFileSync(file);
      } catch {
        hint(`no responsive variants for ${relPosix(paths, file)} — the file could not be read.`);
        continue;
      }
      const intrinsic = imageSize(bytes);
      if (!intrinsic) {
        hint(
          `no responsive variants for ${relPosix(paths, file)} — its dimensions could not be read ` +
            "(corrupt or unsupported image). The original ships as-is."
        );
        continue;
      }
      if (intrinsic.width <= SMALL_IMAGE_MAX_WIDTH) continue;
      const hash = crypto.createHash("sha256").update(bytes).digest("hex").slice(0, 24);
      const targets = widths.filter(
        (w) =>
          w < intrinsic.width && !fs.existsSync(path.join(path.dirname(file), `${stem}@${w}${ext}`))
      );
      if (targets.length === 0) continue;
      /** @type {"jpeg" | "png" | "webp"} */
      const format = ext === ".png" ? "png" : ext === ".webp" ? "webp" : "jpeg";
      for (const width of targets) {
        const cacheFile = path.join(cacheDir, `${hash}@${width}${ext}`);
        const distOut = path.join(paths.distRoot, path.dirname(rel), `${stem}@${width}${ext}`);
        if (fs.existsSync(cacheFile)) {
          emitVariant(file, width, cacheFile, distOut);
          stats.cached++;
        } else {
          const job = { source: file, out: cacheFile, width, format };
          pending.push(job);
          waiting.push({ job, distOut });
          if (!needingSharp.includes(relPosix(paths, file)))
            needingSharp.push(relPosix(paths, file));
        }
      }
    }
  }

  if (pending.length > 0) {
    const result = runJobs(pending);
    if (result.unavailable) {
      stats.unavailable = true;
      hint(
        `${needingSharp.length} image${needingSharp.length === 1 ? "" : "s"} could gain responsive ` +
          `variants (${needingSharp.join(", ")}). Run \`npm i -D sharp\` to generate them at build time.`
      );
    } else {
      const failed = new Map(result.failed.map((f) => [`${f.file}@${f.width}`, f.error]));
      for (const { job, distOut } of waiting) {
        const error = failed.get(`${job.source}@${job.width}`);
        if (error !== undefined) {
          hint(
            `no ${job.width}px variant for ${relPosix(paths, job.source)} — sharp failed: ${error}. ` +
              "The image ships without that variant."
          );
          continue;
        }
        emitVariant(job.source, job.width, job.out, distOut);
        stats.generated++;
      }
    }
  }

  for (const list of variants.values()) list.sort((a, b) => a - b);
  return { variants, ...stats };
}

/**
 * The default resize seam: run every pending job in ONE child process (the
 * build is synchronous; sharp is not), communicating through temp JSON files
 * rather than stdio so a large job list never hits a pipe buffer. The worker
 * always writes a results file — a missing or unparsable one means the child
 * itself died (crashed, or killed by the spawn timeout), which is reported as
 * `unavailable` (the build then behaves as if sharp were absent: a hint, no
 * variants, no failure).
 * @param {ResizeJob[]} jobs
 * @param {(cmd: string, args: string[], opts: object) => unknown} [spawn]
 *   Injectable for tests; the real one is `spawnSync`.
 * @param {number} [timeoutMs] The worker is killed after this long (default
 *   two minutes), so a hung sharp call cannot stall a build forever. The kill
 *   lands in the same `unavailable` path as any other dead child.
 * @returns {ResizeResult}
 */
export function runResizeJobs(jobs, spawn = /** @type {any} */ (spawnSync), timeoutMs = 120000) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "wd-img-variants-"));
  try {
    const jobsFile = path.join(dir, "jobs.json");
    const resultsFile = path.join(dir, "results.json");
    fs.writeFileSync(jobsFile, JSON.stringify(jobs));
    spawn(process.execPath, [WORKER_PATH, jobsFile, resultsFile], {
      stdio: ["ignore", "ignore", "inherit"],
      timeout: timeoutMs
    });
    if (!fs.existsSync(resultsFile)) return { unavailable: true, failed: [] };
    try {
      return JSON.parse(fs.readFileSync(resultsFile, "utf8"));
    } catch {
      return { unavailable: true, failed: [] };
    }
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

/**
 * A project-relative, POSIX-separated path for hint messages.
 * @param {Paths} paths
 * @param {string} file Absolute path.
 * @returns {string}
 */
function relPosix(paths, file) {
  return path.relative(paths.cwd, file).replaceAll(path.sep, "/");
}

/**
 * Match the router's (and `emitPageAssets`') hidden-path convention: anything
 * below a `.`, `-`, or `_` segment is private framework input, not public
 * output — variants for it would never be served, so it is not scanned.
 * @param {string} rel
 * @returns {boolean}
 */
function hasHiddenPathSegment(rel) {
  return rel.split(path.sep).some((segment) => /^[._-]/.test(segment));
}

/**
 * All files under `dir`, recursively. Mirrors the builder's own walker; kept
 * local so this module does not import the builder (which imports this).
 * @param {string} dir
 * @returns {string[]}
 */
function walk(dir) {
  /** @type {string[]} */
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(abs));
    else files.push(abs);
  }
  return files;
}
